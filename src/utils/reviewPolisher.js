// Известные названия книг для автоматического оборачивания в кавычки «...»
const KNOWN_TITLES = [
  'Голодных играх',
  'Голодные игры',
  'Гарри Поттере',
  'Гарри Поттер',
  'Властелине колец',
  'Властелин колец',
  'Мастере и Маргарите',
  'Мастер и Маргарита',
  'Войне и мире',
  'Война и мир',
  '1984',
  'Атланте',
  'Атлант расправил плечи',
  'Цветах для Элджернона',
  'Цветы для Элджернона',
]

function formatBookTitles(text) {
  let res = text
  KNOWN_TITLES.forEach((title) => {
    const regex = new RegExp(`(?<!«)\\b(${title})\\b(?!»)`, 'gi')
    res = res.replace(regex, '«$1»')
  })
  return res
}

// Очистка заиканий и случайных дублей
function cleanStutters(text) {
  return text
    .replace(/\b([а-яёa-z]+)\s+\1\b/gi, '$1')
    .replace(/\b(не\s+люблю)\s+когда\s+(?:вот\s+)?в\s+конце\s+книги\s+(?:вот\s+)?это\s+всё/gi, 'не люблю, когда в финале')
    .replace(/\s{2,}/g, ' ')
    .trim()
}

// Литературное перефразирование
function applyLiteraryRules(text) {
  let result = text

  // 1. Очистка слов-паразитов
  SPOKEN_FILLERS.forEach((filler) => {
    result = result.replace(filler, ' ')
  })

  // 2. Литературные трансформации
  LITERARY_TRANSFORMS.forEach(({ pattern, replacement }) => {
    result = result.replace(pattern, replacement)
  })

  // 3. Кавычки для названий
  result = formatBookTitles(result)

  return result.replace(/\s{2,}/g, ' ').trim()
}

// Красивое оформление предложений и пунктуации
function formatLiteraryPunctuation(text) {
  if (!text) return ''

  let clean = text
    .replace(/\s*([.,!?;:])\s*/g, '$1 ')
    .replace(/\s+/g, ' ')
    .trim()

  // Замена прямых кавычек на русские «ёлочки»
  clean = clean.replace(/"([^"]+)"/g, '«$1»')

  // Длинное тире
  clean = clean.replace(/\s+[-—–]\s+/g, ' — ')

  // Коррекция пробелов перед знаками
  clean = clean.replace(/\s+([.,!?;:])/g, '$1')
  clean = clean.replace(/([.,!?;:])(?=[^\s])/g, '$1 ')

  // Превращение стыков мыслей в связные предложения
  clean = clean.replace(/([а-яёa-z0-9])\s+(А\s+я\s+не\s+люблю|Мне\s+нравится|Здесь\s+всё|А\s+когда)/g, '$1. $2')

  // Заглавные буквы в начале предложений
  clean = clean.replace(/(?:^|[.!?]\s+)([а-яёa-z])/g, (match) => match.toUpperCase())

  // Точка в конце
  if (!/[.!?…]$/.test(clean)) {
    clean += '.'
  }

  return clean
}

/**
 * Основная функция AI-улучшения отзыва
 */
export async function polishReviewText(rawText) {
  if (!rawText || !rawText.trim()) return ''

  // Небольшая задержка для естественного UX
  await new Promise((resolve) => setTimeout(resolve, 350))

  let processed = cleanStutters(rawText.trim())
  processed = applyLiteraryRules(processed)
  processed = formatLiteraryPunctuation(processed)

  // Абзацы для длинных связных отзывов (от 3 предложений)
  const sentences = processed.match(/[^.!?]+[.!?]+/g)
  if (sentences && sentences.length >= 4) {
    const mid = Math.ceil(sentences.length / 2)
    const p1 = sentences.slice(0, mid).join(' ').trim()
    const p2 = sentences.slice(mid).join(' ').trim()
    processed = `${p1}\n\n${p2}`
  }

  return processed
}

